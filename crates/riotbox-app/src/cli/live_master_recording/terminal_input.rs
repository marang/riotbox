//! Private V2 input: terminal resources and normalized tokens, never action truth.
use std::io;

use crossterm::event::KeyEvent;

#[cfg(any(target_os = "linux", test))]
mod byte_input;
#[cfg(target_os = "linux")]
mod linux;

#[cfg(target_os = "linux")]
use byte_input::ByteInput;
#[cfg(target_os = "linux")]
use linux::{CrosstermRawMode, NonBlockingReader, RawModeGuard};
#[cfg(target_os = "linux")]
use std::io::{IsTerminal, Stdin};

pub(super) trait RecordingInput {
    /// Tokens describe received input, not physical key kind or modifiers.
    fn poll_event(&mut self) -> io::Result<Option<KeyEvent>>;
}

pub(super) struct TerminalInput {
    #[cfg(target_os = "linux")]
    input: ByteInput<NonBlockingReader<Stdin>>,
    #[cfg(target_os = "linux")]
    raw_mode: RawModeGuard<CrosstermRawMode>,
    #[cfg(target_os = "linux")]
    active: bool,
}

impl TerminalInput {
    pub(super) fn open() -> io::Result<Self> {
        #[cfg(target_os = "linux")]
        {
            let stdin = io::stdin();
            if !stdin.is_terminal() {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidInput,
                    "live recording terminal input requires stdin to be a TTY",
                ));
            }
            let (reader, raw_mode) = linux::acquire(stdin, CrosstermRawMode)?;
            Ok(Self {
                input: ByteInput::new(reader),
                raw_mode,
                active: true,
            })
        }
        #[cfg(not(target_os = "linux"))]
        {
            Err(io::Error::new(
                io::ErrorKind::Unsupported,
                "live recording terminal input V2 is supported on Linux only",
            ))
        }
    }

    /// Both guards independently retry unfinished restoration on Drop.
    pub(super) fn restore(&mut self) -> io::Result<()> {
        #[cfg(target_os = "linux")]
        {
            self.active = false;
            let reader = self.input.reader_mut();
            let raw_mode = &mut self.raw_mode;
            linux::restore_resources(|| reader.restore(), || raw_mode.restore())
        }
        #[cfg(not(target_os = "linux"))]
        {
            Ok(())
        }
    }
}

impl RecordingInput for TerminalInput {
    fn poll_event(&mut self) -> io::Result<Option<KeyEvent>> {
        #[cfg(target_os = "linux")]
        {
            if !self.active {
                return Err(io::Error::new(
                    io::ErrorKind::NotConnected,
                    "live recording terminal input is already restored",
                ));
            }
            self.input.poll_event()
        }
        #[cfg(not(target_os = "linux"))]
        {
            Err(io::Error::new(
                io::ErrorKind::Unsupported,
                "live recording terminal input V2 is supported on Linux only",
            ))
        }
    }
}

/// Generated bytes through the production decoder, without terminal resources.
#[cfg(test)]
pub(super) fn generated_byte_input(
    scheduled: std::collections::VecDeque<(std::time::Duration, u8)>,
    elapsed: std::rc::Rc<std::cell::Cell<std::time::Duration>>,
    attempts: std::rc::Rc<std::cell::RefCell<Vec<std::time::Duration>>>,
) -> impl RecordingInput {
    use std::{cell::Cell, cell::RefCell, collections::VecDeque, rc::Rc, time::Duration};

    use byte_input::{ByteInput, ByteRead, ByteReader};

    struct GeneratedReader {
        scheduled: VecDeque<(Duration, u8)>,
        elapsed: Rc<Cell<Duration>>,
        attempts: Rc<RefCell<Vec<Duration>>>,
    }

    impl ByteReader for GeneratedReader {
        fn read_byte(&mut self) -> io::Result<ByteRead> {
            let now = self.elapsed.get();
            self.attempts.borrow_mut().push(now);
            if self.scheduled.front().is_some_and(|(at, _)| *at <= now) {
                Ok(ByteRead::Byte(self.scheduled.pop_front().unwrap().1))
            } else {
                Ok(ByteRead::Pending)
            }
        }
    }

    struct GeneratedInput {
        input: ByteInput<GeneratedReader>,
        elapsed: Rc<Cell<Duration>>,
    }

    impl RecordingInput for GeneratedInput {
        fn poll_event(&mut self) -> io::Result<Option<KeyEvent>> {
            self.input.poll_at(self.elapsed.get())
        }
    }

    GeneratedInput {
        input: ByteInput::new(GeneratedReader {
            scheduled,
            elapsed: Rc::clone(&elapsed),
            attempts,
        }),
        elapsed,
    }
}
